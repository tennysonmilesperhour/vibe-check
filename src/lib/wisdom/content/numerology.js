// Reduce any number to a numerology key (1-9, or master 11/22/33 kept intact).
export function reduceToKey(n) {
  let num = Number(n);
  if (!Number.isFinite(num) || num <= 0) return null;
  while (num > 9 && num !== 11 && num !== 22 && num !== 33) {
    num = String(num).split("").reduce((a, d) => a + Number(d), 0);
  }
  return NUMBERS[num] ? num : null;
}
